
import React, { useState } from 'react';
import { AnalysisReport, Location, Priority, Role, Status, User } from '../types';
import { MailIcon, PhoneIcon, CalendarIcon, TrashIcon, UserCircleIcon } from './icons';
import ConfirmationModal from './ConfirmationModal';
import InspectorUpdateForm from './InspectorUpdateForm';

interface ReportDisplayProps {
  report: AnalysisReport;
  location: Location;
  currentUser: User;
  inspectors: User[];
  onStatusChange: (reportId: string, reportedBy: string, newStatus: Status) => void;
  onDelete: (reportId: string, reportedBy: string) => void;
  onInspectorUpdate: (reportId: string, reportedBy: string, review: string, photoFile: File) => void;
  onAssignInspector: (reportId: string, reportedBy: string, inspectorUsername: string | undefined) => void;
  isLoading: boolean;
}

const priorityStyles: { [key in Priority]: { bg: string; text: string; ring: string } } = {
  [Priority.Low]: { bg: 'bg-green-800/50', text: 'text-green-300', ring: 'ring-green-500' },
  [Priority.Medium]: { bg: 'bg-yellow-800/50', text: 'text-yellow-300', ring: 'ring-yellow-500' },
  [Priority.High]: { bg: 'bg-red-800/50', text: 'text-red-300', ring: 'ring-red-500' },
};

const statusStyles: { [key in Status]: { bg: string; text: string; } } = {
  [Status.Reported]: { bg: 'bg-blue-800/50', text: 'text-blue-300' },
  [Status.InProgress]: { bg: 'bg-purple-800/50', text: 'text-purple-300' },
  [Status.Resolved]: { bg: 'bg-gray-700/60', text: 'text-gray-400' },
};

const ReportDisplay: React.FC<ReportDisplayProps> = ({ report, location, currentUser, inspectors, onStatusChange, onDelete, onInspectorUpdate, onAssignInspector, isLoading }) => {
  const [isDeleteModalOpen, setIsDeleteModalOpen] = useState(false);

  const pStyles = priorityStyles[report.priority];
  const sStyles = statusStyles[report.status];

  const handleSendEmail = () => {
    const subject = `[${report.priority} Priority] Issue Report: ${report.problem}`;
    const body = `
Dear ${report.recipient.name},

An issue has been identified and requires your attention.

Problem: ${report.problem}
Category: ${report.problemCategory}
Status: ${report.status}
Priority: ${report.priority}
Location: https://www.google.com/maps?q=${location.latitude},${location.longitude}
Assigned Inspector: ${report.inspector.name} (${report.inspector.phone})

Generated Report:
-----------------
${report.report}
-----------------

Suggested Remediation:
-----------------
${report.remediationSteps}
-----------------

This report was generated by ${report.reportedBy} on ${new Date(report.createdAt).toLocaleString()}.

Regards,
AI Issue Reporter
    `;
    window.location.href = `mailto:${report.recipient.email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  };
  
  const handleCall = (phone: string) => {
    window.location.href = `tel:${phone}`;
  };

  const handleConfirmDelete = () => {
    onDelete(report.id, report.reportedBy);
    setIsDeleteModalOpen(false);
  };

  const isAdmin = currentUser.role === Role.Admin;
  const isInspector = currentUser.role === Role.IssueInspector;
  const canInspectorUpdate = isInspector && report.status === Status.Reported && report.assignedInspectorUsername === currentUser.username;
  const hasInspectorReview = report.inspectorReview && report.status !== Status.Resolved;

  return (
    <>
      <div className="w-full bg-gray-800 border border-gray-700 rounded-xl shadow-lg p-6 space-y-6 animate-fade-in">
        
        {report.imageUrl && (
            <div className="mb-4">
                <h3 className="text-sm font-semibold text-gray-400 uppercase tracking-wider mb-2">Reported Image</h3>
                <img src={report.imageUrl} alt="Reported issue" className="w-full max-h-96 object-contain rounded-lg bg-black" />
            </div>
        )}
        
        <div className="flex flex-col sm:flex-row justify-between items-start gap-4">
          <h2 className="text-2xl font-bold text-white flex-1">{report.problem}</h2>
          <div className="flex flex-col sm:flex-row sm:items-center gap-2 flex-shrink-0">
            <span className={`inline-flex items-center px-3 py-1 rounded-full text-sm font-semibold bg-indigo-800/50 text-indigo-300 ring-1 ring-inset ring-indigo-500`}>
              {report.problemCategory}
            </span>
            <span className={`inline-flex items-center px-3 py-1 rounded-full text-sm font-semibold ${pStyles.bg} ${pStyles.text} ring-1 ring-inset ${pStyles.ring}`}>
              {report.priority} Priority
            </span>
          </div>
        </div>

        <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 p-3 bg-gray-900/50 rounded-lg">
          <div className="flex items-center gap-3 text-sm text-gray-400">
              <CalendarIcon className="w-5 h-5"/>
              <span>Reported: {new Date(report.createdAt).toLocaleString()}</span>
              {(isAdmin || isInspector) && <span className="text-gray-500">by <strong className="text-gray-300">{report.reportedBy}</strong></span>}
          </div>
          <div className="flex items-center gap-2">
              <label htmlFor={`status-${report.id}`} className="text-sm font-semibold text-gray-400">Status:</label>
              <select
                  id={`status-${report.id}`}
                  value={report.status}
                  disabled={!isAdmin}
                  onChange={(e) => onStatusChange(report.id, report.reportedBy, e.target.value as Status)}
                  className={`rounded-md px-3 py-1 text-sm font-semibold border-none focus:ring-2 focus:ring-offset-2 focus:ring-offset-gray-900 focus:ring-cyan-500 transition-colors ${sStyles.bg} ${sStyles.text} disabled:opacity-70 disabled:cursor-not-allowed`}
              >
                  {Object.values(Status).map(s => <option key={s} value={s}>{s}</option>)}
              </select>
          </div>
        </div>

        <div>
          <h3 className="text-sm font-semibold text-gray-400 uppercase tracking-wider mb-2">Detailed Report</h3>
          <p className="text-gray-300 whitespace-pre-wrap">{report.report}</p>
        </div>

        <div>
          <h3 className="text-sm font-semibold text-gray-400 uppercase tracking-wider mb-2">Suggested Remediation</h3>
          <p className="text-gray-300 whitespace-pre-wrap">{report.remediationSteps}</p>
        </div>

        {report.inspectorReview && (
            <div className="bg-gray-900/50 p-4 rounded-lg space-y-3 border border-teal-700/50">
                <div className="flex justify-between items-start">
                    <h3 className="text-base font-semibold text-teal-300">Inspector's Update</h3>
                    {isAdmin && hasInspectorReview && (
                        <button 
                            onClick={() => onStatusChange(report.id, report.reportedBy, Status.Resolved)}
                            className="px-3 py-1 text-xs font-bold text-white bg-green-600 rounded-md hover:bg-green-500 transition-colors"
                        >
                            Mark as Resolved
                        </button>
                    )}
                </div>
                {report.inspectorPhotoUrl && (
                    <div>
                        <img src={report.inspectorPhotoUrl} alt="Inspector's evidence" className="max-h-80 w-auto rounded-md object-contain mx-auto border border-gray-700" />
                    </div>
                )}
                <div>
                    <h4 className="text-sm font-semibold text-gray-400 uppercase tracking-wider mb-1">Review Notes</h4>
                    <p className="text-gray-300 whitespace-pre-wrap">{report.inspectorReview}</p>
                </div>
                {report.inspectorUpdateAt && (
                    <p className="text-xs text-gray-500 text-right">Submitted on: {new Date(report.inspectorUpdateAt).toLocaleString()}</p>
                )}
            </div>
        )}

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-sm">
          <div className="bg-gray-900/50 p-4 rounded-lg space-y-2">
              <p className="font-semibold text-gray-400">Recipient</p>
              <p className="text-white font-medium text-base">{report.recipient.name}</p>
              <div className="flex items-center gap-2 text-gray-300">
                  <MailIcon className="w-4 h-4 text-gray-400 flex-shrink-0"/>
                  <span>{report.recipient.email}</span>
              </div>
          </div>
          
          <div className="bg-gray-900/50 p-4 rounded-lg space-y-2">
              <div className="flex justify-between items-start">
                <p className="font-semibold text-gray-400">Assigned Inspector</p>
                {isAdmin && report.inspector.phone !== 'N/A' && (
                  <button onClick={() => handleCall(report.inspector.phone)} className="flex-shrink-0 px-3 py-1.5 text-xs font-semibold text-cyan-200 bg-cyan-800/50 rounded-md hover:bg-cyan-700/50 transition-colors">CALL</button>
                )}
              </div>
              {isAdmin ? (
                <select 
                  value={report.assignedInspectorUsername || ''}
                  onChange={(e) => onAssignInspector(report.id, report.reportedBy, e.target.value || undefined)}
                  className="w-full bg-gray-800 border border-gray-600 rounded-md p-2 text-white font-medium text-base focus:ring-cyan-500 focus:border-cyan-500"
                >
                  <option value="">Unassigned</option>
                  {inspectors.map(inspector => (
                    <option key={inspector.username} value={inspector.username}>{inspector.username}</option>
                  ))}
                </select>
              ) : (
                 <p className="text-white font-medium text-base">{report.inspector.name}</p>
              )}
               <div className="flex items-center gap-2 text-gray-300">
                  <PhoneIcon className="w-4 h-4 text-gray-400 flex-shrink-0"/>
                  <span>{report.inspector.phone}</span>
              </div>
          </div>
        </div>
        
        {canInspectorUpdate && (
            <InspectorUpdateForm
                onSubmit={(review, photoFile) => onInspectorUpdate(report.id, report.reportedBy, review, photoFile)}
                isSubmitting={isLoading}
            />
        )}

        <div className="pt-4 border-t border-gray-700 flex flex-col sm:flex-row gap-4">
          {isAdmin && (
            <button 
              onClick={() => setIsDeleteModalOpen(true)}
              className="w-full flex items-center justify-center gap-2 px-6 py-3 bg-red-800/80 text-red-200 font-bold rounded-lg hover:bg-red-700/80 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-offset-gray-800 focus:ring-red-600 transition-all duration-200"
            >
              <TrashIcon className="w-5 h-5" />
              Delete Report
            </button>
          )}
          <button 
            onClick={handleSendEmail} 
            className="w-full flex items-center justify-center gap-2 px-6 py-3 bg-cyan-600 text-white font-bold rounded-lg hover:bg-cyan-500 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-offset-gray-800 focus:ring-cyan-500 transition-all duration-200"
          >
            <MailIcon className="w-5 h-5" />
            Send Report via Email
          </button>
        </div>
      </div>
      <ConfirmationModal
        isOpen={isDeleteModalOpen}
        onClose={() => setIsDeleteModalOpen(false)}
        onConfirm={handleConfirmDelete}
        title="Confirm Deletion"
        message="Are you sure you want to permanently delete this report? This action cannot be undone."
      />
    </>
  );
};

export default ReportDisplay;